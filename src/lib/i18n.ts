export type Lang = "pt" | "en";
export type Key = keyof typeof pt;
const dict = { pt, en };

export const lang = writable<Lang>("pt");

export const t = derived(lang, ($l) => (key: Key, params?: Record<string, string | number>) => {
  let s: string = dict[$l][key] ?? key;
  if (params) for (const k in params) s = s.replaceAll(`{${k}}`, String(params[k]));
  return s;
});

export const locale = derived(lang, ($l) => ($l === "pt" ? "pt-BR" : "en-US"));
